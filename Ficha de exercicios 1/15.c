//Questão 15. A diretiva #include, amplamente utilizada no topo dos arquivos C, é classificada como:

// a) Uma instrução C nativa (compilada diretamente em linguagem de máquina).
// b) Uma instrução específica de linguagens de programação orientadas a objetos.
// c) Uma diretiva especial para o pré-processador C, executada antes da compilação.
// d) Um objeto de classe de armazenamento dinâmico na memória heap.

//Resposta: c) Uma diretiva especial para o pré-processador C, executada antes da compilação.
//Justificativa: A diretiva #include é processada pelo pré-processador, que substitui a diretiva pelo conteúdo do arquivo especificado antes que o compilador C inicie a compilação do código-fonte. 
// Isso permite que o código utilize funções, tipos e macros definidos em bibliotecas externas ou outros arquivos de cabeçalho.
